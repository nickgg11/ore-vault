/**
 * {@code /orevault density [radius]} (§3.1 "How the baseline is checked", S12; E4-S4, #254): counts the ore a Vault's
 * generator really wrote over a square of chunks and prints {@link DensityTally}'s S12 verdicts. Read-only: it loads, and
 * so may generate, the chunks it counts, and places or removes nothing. Behind the debug flag and the gamemaster level,
 * like every S44 subcommand, and removed with them at T14.
 *
 * <p>The shape is the Epic 4 triage's (DEV-E4-9). The argument is a radius in chunks around the source's chunk, 4 by
 * default (9 by 9, S12's 81) and at most 10 (441): the count runs on the server thread and loads each chunk synchronously,
 * which is how vanilla's commands load chunks, and an open-ended square would hold the tick past the dedicated server's
 * watchdog. The level is the source's, so the console runs it with
 * {@code execute in orevault:vault_<team> run orevault density}, and a level whose generator is not a Vault's is refused.
 * Blocks are matched to the published {@link OreTable} through a map from {@code Block} to entry built once a run, so the
 * count never builds an id string per block. The elapsed time is logged.
 *
 * <p>Which chunks are this build's (triage open point 5, DEV-E4-10, ARCH-E4-17): the generator keeps a memory-only set of
 * the chunks it filled this session. A chunk in it was generated by this build; one that is not came from disk and may
 * predate it, so the command warns. After a restart every chunk warns, which over-warns and never under-warns. No access
 * transformer, no save data, nothing read from {@code SavedData} (rule 1).
 */
public final class DensityCommand {
    public static final int DEFAULT_RADIUS = 4;
    public static final int MAX_RADIUS = 10;

    static final String NOT_A_VAULT = "commands.orevault.density.not_a_vault";
    static final String CHUNKS = "commands.orevault.density.chunks";
    static final String STALE = "commands.orevault.density.stale";
    static final String ELAPSED = "commands.orevault.density.elapsed";

    private static final Logger LOG = LoggerFactory.getLogger(DensityCommand.class);
    private static final String TAG = "[orevault-debug] ";
    private static final int SECTION = SectionPos.SECTION_SIZE;

    private DensityCommand() {
    }

    /** Every translation key this command sends, for the gametest that holds {@code en_us} complete. */
    public static List<String> messageKeys() {
        return List.of(NOT_A_VAULT, CHUNKS, STALE, ELAPSED);
    }

    /**
     * What one run counted.
     *
     * @param tally the placed ore, by band, rarity, slab and ore
     * @param generatedByThisRun chunks this generator had not filled before the run and had after it
     * @param generatedEarlier chunks it had already filled this session
     * @param notThisSession chunks it did not fill this session: loaded from disk, so possibly older than this build
     */
    public record Count(DensityTally tally, int generatedByThisRun, int generatedEarlier, int notThisSession) {
    }

    static LiteralArgumentBuilder<CommandSourceStack> node(Predicate<CommandSourceStack> allowed) {
        return Commands.literal("density").requires(allowed)
                .executes(context -> run(context.getSource(), DEFAULT_RADIUS))
                .then(Commands.argument("radius", IntegerArgumentType.integer(0, MAX_RADIUS))
                        .executes(context -> run(context.getSource(), IntegerArgumentType.getInteger(context, "radius"))));
    }

    private static int run(CommandSourceStack source, int radius) {
        long started = System.nanoTime();
        ServerLevel level = source.getLevel();
        if (!(level.getChunkSource().getGenerator() instanceof VaultChunkGenerator generator)) {
            MutableComponent refusal = tagged(Component.translatable(NOT_A_VAULT, level.dimension().identifier().toString()));
            source.sendFailure(refusal);
            LOG.info("{}", refusal.getString());
            return 0;
        }
        BlockPos at = BlockPos.containing(source.getPosition());
        int centreX = at.getX() >> 4;
        int centreZ = at.getZ() >> 4;
        Count count = count(level, generator, centreX, centreZ, radius);
        long millis = (System.nanoTime() - started) / 1_000_000;

        print(source, Component.literal(level.dimension().identifier() + ", radius " + radius + " around chunk " + centreX
                + "," + centreZ));
        for (String line : count.tally().lines()) {
            print(source, Component.literal(line));
        }
        int counted = count.tally().chunks();
        print(source, Component.translatable(CHUNKS, counted, count.generatedByThisRun(), count.generatedEarlier(),
                count.notThisSession()));
        if (count.notThisSession() > 0) {
            MutableComponent warning = tagged(Component.translatable(STALE, count.notThisSession(), counted));
            source.sendFailure(warning);
            LOG.warn("{}", warning.getString());
        }
        print(source, Component.translatable(ELAPSED, millis));
        return 1;
    }

    /**
     * Counts the square of chunks {@code radius} around a chunk, loading (and so generating) each one. On the server thread:
     * this reads the world and the published table, never the generator's worker state beyond its concurrent set.
     */
    public static Count count(ServerLevel level, VaultChunkGenerator generator, int centreX, int centreZ, int radius) {
        VaultVariant variant = generator.variant();
        OreIndex ores = OreIndex.of(VaultChunkGenerator.publishedOres().table());
        int side = 2 * radius + 1;
        DensityTally tally = new DensityTally(OreBaseline.BASE, variant, side * side);
        // Read who was filled before any chunk loads: loading one chunk at full status generates its neighbours too, so a
        // per-chunk "before" taken inside the loop counts a neighbour this run generated as earlier.
        boolean[][] filledBefore = new boolean[side][side];
        for (int dx = 0; dx < side; dx++) {
            for (int dz = 0; dz < side; dz++) {
                filledBefore[dx][dz] = generator.filledThisSession(centreX - radius + dx, centreZ - radius + dz);
            }
        }
        int byThisRun = 0;
        int earlier = 0;
        int notThisSession = 0;
        for (int dx = 0; dx < side; dx++) {
            for (int dz = 0; dz < side; dz++) {
                int chunkX = centreX - radius + dx;
                int chunkZ = centreZ - radius + dz;
                LevelChunk chunk = level.getChunk(chunkX, chunkZ);
                if (filledBefore[dx][dz]) {
                    earlier++;
                } else if (generator.filledThisSession(chunkX, chunkZ)) {
                    byThisRun++;
                } else {
                    notThisSession++;
                }
                countChunk(chunk, variant, ores, tally);
            }
        }
        return new Count(tally, byThisRun, earlier, notThisSession);
    }

    /**
     * Every band layer of one chunk, a section at a time; a section with no ore block in its palette is skipped whole. Ore
     * outside the bands (one a player carried up and placed) is not counted: S12 is about what the generator wrote.
     */
    private static void countChunk(LevelChunk chunk, VaultVariant variant, OreIndex ores, DensityTally tally) {
        long[] perLayer = new long[ores.entries().size()];
        for (int index = 0; index < chunk.getSectionsCount(); index++) {
            LevelChunkSection section = chunk.getSection(index);
            if (section.hasOnlyAir() || !section.maybeHas(state -> ores.byBlock().containsKey(state.getBlock()))) {
                continue;
            }
            int baseY = SectionPos.sectionToBlockCoord(chunk.getMinSectionY() + index);
            for (int y = 0; y < SECTION; y++) {
                Optional<Band> band = DensityTally.bandAt(variant, baseY + y);
                if (band.isEmpty()) {
                    continue;
                }
                for (int z = 0; z < SECTION; z++) {
                    for (int x = 0; x < SECTION; x++) {
                        Integer entry = ores.byBlock().get(section.getBlockState(x, y, z).getBlock());
                        if (entry != null) {
                            perLayer[entry]++;
                        }
                    }
                }
                for (int entry = 0; entry < perLayer.length; entry++) {
                    if (perLayer[entry] > 0) {
                        OreTable.Entry ore = ores.entries().get(entry);
                        tally.add(band.get(), baseY + y, ore.rarity(), ore.groupId(), perLayer[entry]);
                        perLayer[entry] = 0;
                    }
                }
            }
        }
    }

    /**
     * The published table as a map from {@code Block} to the entry's index, built once a run: the same answer as
     * {@link OreTable#lookup} on the block's id, for every block of every group, without an id string per block.
     */
    private record OreIndex(List<OreTable.Entry> entries, Map<Block, Integer> byBlock) {
        static OreIndex of(OreTable table) {
            List<OreTable.Entry> entries = new ArrayList<>(table.entries());
            Map<Block, Integer> byBlock = new IdentityHashMap<>();
            for (int index = 0; index < entries.size(); index++) {
                for (String id : entries.get(index).blocks()) {
                    Identifier key = Identifier.parse(id);
                    if (!BuiltInRegistries.BLOCK.containsKey(key)) {
                        throw new IllegalStateException("The ore table names " + id + ", which is not a block");
                    }
                    byBlock.put(BuiltInRegistries.BLOCK.getValue(key), index);
                }
            }
            return new OreIndex(List.copyOf(entries), byBlock);
        }
    }

    private static MutableComponent tagged(Component message) {
        return Component.literal(TAG).append(message);
    }

    private static void print(CommandSourceStack source, Component message) {
        MutableComponent line = tagged(message);
        source.sendSuccess(() -> line, false);
        LOG.info("{}", line.getString());
    }
}
